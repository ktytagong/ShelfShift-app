"""The assumptions table is generated from reference/, never written by hand (DATA-06).

One row per leaf of the public reference files (policy, world, scenarios), with its value, unit, type, source and
note, sorted by dotted path. The hidden markdown response (reference/hidden.json) is never walked, so it can never
reach the table (03-01 T-3-02). Run `python -m data.assumptions` to regenerate `data/reference/assumptions.md`; a
test regenerates it and compares bytes with the committed file.
"""
from __future__ import annotations

import json
import pathlib

from data import config

OUT = pathlib.Path(__file__).resolve().parent / "reference"
NAME = "assumptions.md"
LABEL = "Synthetic data · hypothetical scenario"
TYPE_LEGEND = ("Types: Data = synthetic world input; Policy = store or engine policy value; Adoptable = a value a "
               "manager can adopt through an override; Reported = a measured benchmark, never a target; "
               "Assumption = assumed, pending retailer.")
COLUMNS = ("Setting", "Value", "Unit", "Type", "Source", "Note")


def rows(ref_in: pathlib.Path | str = config.REF_IN) -> list[dict]:
    """Every leaf of the public reference files as {path, value, unit, type, source, note}, sorted by path."""
    ref_in = pathlib.Path(ref_in)
    out = []
    for name in config.PUBLIC:  # policy, world, scenarios; never hidden
        for path, leaf in config.leaves(config.read(ref_in / f"{name}.json"), name):
            out.append({"path": path, "value": leaf["value"], "unit": leaf.get("unit", ""), "type": leaf["type"],
                        "source": leaf["source"], "note": leaf.get("note", "")})
    return sorted(out, key=lambda row: row["path"])


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")  # a pipe or line break would split the table row


def render(rows: list[dict], fingerprint: str) -> str:
    """The Markdown table for `rows`, stamped with the reference fingerprint. Ends with exactly one newline."""
    lines = [
        "# Assumptions table",
        "",
        LABEL,
        "",
        f"Generated by `python -m data.assumptions` from `reference/` (fingerprint {fingerprint}). Never edit by hand.",
        "",
        TYPE_LEGEND,
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "|".join("---" for _ in COLUMNS) + "|",
    ]
    for row in rows:
        cells = (row["path"], json.dumps(row["value"], ensure_ascii=False), row["unit"], row["type"], row["source"],
                 row["note"])
        lines.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    return "\n".join(lines) + "\n"


def write(out: pathlib.Path | str = OUT, ref_in: pathlib.Path | str = config.REF_IN) -> pathlib.Path:
    """Write `<out>/assumptions.md` (UTF-8, atomically) from the reference files in `ref_in`."""
    out = pathlib.Path(out)
    out.mkdir(parents=True, exist_ok=True)
    path = out / NAME
    config.atomic_write(path, render(rows(ref_in), config.fingerprint(ref_in)))
    return path


def main() -> None:
    path = write()
    print(f"wrote {path} ({len(rows())} rows)")


if __name__ == "__main__":
    main()
